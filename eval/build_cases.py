#!/usr/bin/env python3
"""Rebuild the committed eval corpus under eval/cases/.

Every case is synthetic, generated by ``blameshift.simulate`` with a fixed
seed, so the corpus is fully reproducible:

    python eval/build_cases.py

Case layout (one directory per case): series.csv, changes.json, truth.json.
``truth.json`` is the answer key used by ``blameshift eval``; it is never
read by ``blameshift run``.
"""

from __future__ import annotations

import dataclasses
import shutil
from pathlib import Path

from blameshift.simulate import generate, generate_benign, write_demo

CASES_DIR = Path(__file__).resolve().parent / "cases"

LOOKBACK_S = 48.0 * 3600.0  # default blame lookback window


def main() -> None:
    if CASES_DIR.exists():
        shutil.rmtree(CASES_DIR)
    CASES_DIR.mkdir(parents=True)

    # Planted regressions: the detector should fire near sample 240 and the
    # top suspect should be deploy-482.
    for name, seed in [
        ("case-01-planted-seed7", 7),
        ("case-02-planted-seed11", 11),
        ("case-03-planted-seed23", 23),
    ]:
        write_demo(generate(points=400, seed=seed), CASES_DIR / name)

    # Benign series: no planted shift; any detection is a false positive.
    for name, seed in [("case-04-benign-seed5", 5), ("case-05-benign-seed13", 13)]:
        write_demo(generate_benign(points=400, seed=seed), CASES_DIR / name)

    # Unattributable regression: the shift is real (culprit deploy-482),
    # but every in-window event is stripped from the change log, so the
    # correct output is "unattributed".
    result = generate(points=400, seed=7)
    cp_time = result.points[result.planted_index].timestamp
    stripped = [
        e
        for e in result.events
        if not (cp_time - LOOKBACK_S <= e.timestamp <= cp_time)
    ]
    assert stripped and all(e.id != result.planted_event_id for e in stripped)
    write_demo(dataclasses.replace(result, events=stripped), CASES_DIR / "case-06-unattributable")

    for case in sorted(CASES_DIR.iterdir()):
        print(f"wrote {case.name}")


if __name__ == "__main__":
    main()
